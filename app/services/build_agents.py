"""Author the AGENTS.md that ships with every generated build.

The content is derived here, on the server, from the manifest's own paths —
never from model prose. It gives later agentic edits a small, stable contract:
stack, layout, commands and the rules local models must follow.
"""

from typing import Iterable

MAX_PATHS = 25


def _detect_stack(paths: Iterable[str]) -> tuple[str, str, str, str]:
    names = [p.lower() for p in paths]
    if any(p.endswith("package.json") for p in names):
        return (
            "Node.js (npm)",
            "npm install",
            "npm start",
            "npm test",
        )
    if any(
        p.endswith(("requirements.txt", "pyproject.toml")) or p.endswith(".py")
        for p in names
    ):
        entry = (
            "app.py"
            if "app.py" in names
            else ("main.py" if "main.py" in names else "app.py")
        )
        return (
            "Python (Flask-style app)",
            "python -m venv .venv && . .venv/bin/activate && pip install -r requirements.txt",
            f"python {entry}",
            "python -m pytest -q",
        )
    if any(
        p.endswith(("dockerfile", "docker-compose.yml", "docker-compose.yaml"))
        for p in names
    ):
        return (
            "Containerised app",
            "docker compose build",
            "docker compose up",
            "docker compose run --rm app npm test || true",
        )
    return (
        "See the source files",
        "inspect the README",
        "inspect the entry point",
        "none defined",
    )


def render_agents_md(files: list[dict], target_name: str | None = None) -> str:
    """Return a concise AGENTS.md for the generated app."""
    paths = [
        str(entry.get("path") or "").strip()
        for entry in files or []
        if isinstance(entry, dict) and str(entry.get("path") or "").strip()
    ]
    stack, setup, run, test = _detect_stack(paths)
    lines = [
        "# AGENTS.md",
        "",
        f"Generated by Brainstormer for {target_name or 'this build'}.",
        "Edit this app in small, verifiable slices. Do not rewrite unrelated files.",
        "",
        "## Stack",
        "",
        stack,
        "",
        "## Layout",
        "",
    ]
    lines += [f"- `{p}`" for p in paths[:MAX_PATHS]]
    if len(paths) > MAX_PATHS:
        lines.append(f"- …and {len(paths) - MAX_PATHS} more files")
    lines += [
        "",
        "## Commands",
        "",
        f"- Setup: `{setup}`",
        f"- Run: `{run}`",
        f"- Test: `{test}`",
        "",
        "## Rules",
        "",
        "- Keep source files focused, roughly 150–300 lines.",
        "- Keep pure logic separate from network, file and database I/O.",
        "- Validate inputs and outputs at boundaries; never trust prose as a contract.",
        "- Add or run a fast test for every change before declaring it done.",
        "- Preserve working screens and routes when fixing a single feature.",
        "",
    ]
    return "\n".join(lines)
