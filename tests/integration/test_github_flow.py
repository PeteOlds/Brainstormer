"""GitHub flow coverage: local round-trip plus an optional live scratch repo.

The mocked scrubbing test in tests/unit/test_github_tasks.py always runs.
These tests exercise the real git commands: the local one on every run, and
the live one when CI_TEST_PAT is configured.
"""

import os
import subprocess
import uuid

import pytest

from app.tasks.github_tasks import _run_git

LIVE_REPO = "PeteOlds/brainstormer-ci-scratch"


def _git(*args, cwd=None):
    return subprocess.run(
        args, cwd=cwd, capture_output=True, text=True, check=True
    ).stdout.strip()


def test_local_git_push_roundtrip(tmp_path):
    """No network: prove clone/commit/push works through _run_git."""
    bare = tmp_path / "remote.git"
    _git("git", "init", "--bare", str(bare))
    clone = tmp_path / "clone"
    _run_git(["clone", str(bare), str(clone)], cwd=str(tmp_path))
    _run_git(["config", "user.email", "ci@test.local"], cwd=str(clone))
    _run_git(["config", "user.name", "CI"], cwd=str(clone))
    (clone / "note.txt").write_text("round trip\n")
    _run_git(["add", "note.txt"], cwd=str(clone))
    _run_git(["commit", "-m", "ci round trip"], cwd=str(clone))
    _run_git(["push", "origin", "HEAD"], cwd=str(clone))

    local_sha = _run_git(["rev-parse", "HEAD"], cwd=str(clone))
    remote_sha = _git("git", "--git-dir", str(bare), "rev-parse", "HEAD")
    assert local_sha == remote_sha


@pytest.mark.skipif(
    not os.getenv("GITHUB_TEST_PAT"),
    reason="CI_TEST_PAT is not configured; live GitHub leg skipped",
)
def test_live_github_flow_against_scratch_repo(tmp_path):
    """Real clone/commit/push with the PAT passed out-of-band."""
    token = os.environ["GITHUB_TEST_PAT"]
    branch = "ci-" + uuid.uuid4().hex[:10]
    work = tmp_path / "live"
    pushed = False
    try:
        _run_git(
            ["clone", f"https://github.com/{LIVE_REPO}.git", str(work)],
            cwd=str(tmp_path),
            pat=token,
        )
        _run_git(
            ["config", "user.email", "ci@brainstormer.test"], cwd=str(work), pat=token
        )
        _run_git(["config", "user.name", "Brainstormer CI"], cwd=str(work), pat=token)
        _run_git(["checkout", "-b", branch], cwd=str(work), pat=token)
        (work / f"{branch}.txt").write_text("generated by CI\n")
        _run_git(["add", f"{branch}.txt"], cwd=str(work), pat=token)
        _run_git(["commit", "-m", branch], cwd=str(work), pat=token)
        _run_git(["push", "-u", "origin", branch], cwd=str(work), pat=token)
        pushed = True

        refs = _run_git(
            ["ls-remote", "--heads", "origin", branch], cwd=str(work), pat=token
        )
        assert f"refs/heads/{branch}" in refs
        assert token not in refs
    finally:
        if pushed:
            try:
                _run_git(
                    ["push", "origin", "--delete", branch], cwd=str(work), pat=token
                )
            except RuntimeError:
                pass
